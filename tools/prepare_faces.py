#!/usr/bin/env python3
"""Retain the licensed artist's face as compact editable, indexed 3D geometry.

This runs only at development time. The browser decodes local typed arrays; the
original GLB and pack-specific CC0 evidence remain beside the derivative record.
"""
import base64
import hashlib
import json
from pathlib import Path
import struct
import subprocess
import sys

ROOT=Path(__file__).resolve().parents[1]
DIRECTORY=ROOT/'assets/library/quaternius/merchant_face'


def worker():
    import bpy,bmesh
    from mathutils import Vector
    bpy.ops.wm.read_factory_settings(use_empty=True)
    bpy.ops.import_scene.gltf(filepath=str(DIRECTORY/'source.glb'))
    head=next(o for o in bpy.context.scene.objects if o.type=='MESH' and o.name=='Farmer_Head')
    bpy.context.view_layer.objects.active=head
    for modifier in list(head.modifiers):
        if modifier.type=='ARMATURE':bpy.ops.object.modifier_apply(modifier=modifier.name)
    matrix=head.matrix_world.copy();head.parent=None;head.matrix_world=matrix
    mesh=head.data;bm=bmesh.new();bm.from_mesh(mesh)
    bmesh.ops.delete(bm,geom=[f for f in bm.faces if head.material_slots[f.material_index].name not in {'Skin','Eyebrows','Eye'}],context='FACES')
    # Shared positions must be welded before subdivision. Otherwise each
    # separately exported source triangle turns into a disconnected patch.
    bmesh.ops.remove_doubles(bm,verts=list(bm.verts),dist=.00001)
    bm.to_mesh(mesh);bm.free()
    modifier=head.modifiers.new('Smooth authored face','SUBSURF');modifier.levels=modifier.render_levels=1
    evaluated=head.evaluated_get(bpy.context.evaluated_depsgraph_get());mesh=evaluated.to_mesh();mesh.calc_loop_triangles()
    points=[head.matrix_world@v.co for v in mesh.vertices]
    lo=Vector([min(p[i] for p in points) for i in range(3)]);hi=Vector([max(p[i] for p in points) for i in range(3)])
    center=(lo+hi)/2;height=hi.z-lo.z
    normal_matrix=head.matrix_world.to_3x3().inverted().transposed()
    positions=[];normals=[];colours=[];indices=[];lookup={}
    for triangle in mesh.loop_triangles:
        source_material=head.material_slots[triangle.material_index].material
        shader=source_material.node_tree.nodes.get('Principled BSDF')
        color=list(shader.inputs['Base Color'].default_value)[:3]
        for index in triangle.vertices:
            key=(index,triangle.material_index)
            if key not in lookup:
                lookup[key]=len(positions)//3;p=points[index];n=(normal_matrix@mesh.vertices[index].normal).normalized()
                positions.extend([(p.x-center.x)/height,(p.z-lo.z)/height,-(p.y-center.y)/height])
                normals.extend([n.x,n.z,-n.y]);colours.extend(color)
            indices.append(lookup[key])
    evaluated.to_mesh_clear()
    def pack(values,code):return base64.b64encode(struct.pack('<'+code*len(values),*values)).decode()
    data={'positions':pack(positions,'f'),'normals':pack(normals,'f'),'colours':pack(colours,'f'),'indices':pack(indices,'H'),
        'vertices':len(positions)//3,'triangles':len(indices)//3,'source':'Quaternius / Ultimate Modular Men / Farmer head','license':'CC0-1.0'}
    output=ROOT/'assets/character-faces.js'
    output.write_text('/* Authored face by Quaternius, CC0. Source, fixed mirror revision and pack license: assets/library/quaternius/merchant_face. Generated by tools/prepare_faces.py. */\n'
        +'const CHARACTER_FACES=Object.freeze('+json.dumps({'merchant':data},separators=(',',':'))+');\n')
    (DIRECTORY/'runtime-metadata.json').write_text(json.dumps({'source':'source.glb','runtime':'assets/character-faces.js','vertices':data['vertices'],'triangles':data['triangles'],'bytes':output.stat().st_size,'sha256':hashlib.sha256(output.read_bytes()).hexdigest(),'derivation':'Authored face and hair only, material colour regions retained; source seams welded, one subdivision, indexed typed-array geometry, normalized to unit height. Costume and straw hat excluded.'},indent=2)+'\n')
    print('Authored face:',data['vertices'],'vertices,',data['triangles'],'triangles,',output.stat().st_size,'JavaScript bytes')


if __name__=='__main__':
    if '--worker' in sys.argv:worker()
    else:
        manifest=json.loads((DIRECTORY/'manifest.json').read_text())
        if manifest['license']!='CC0-1.0' or hashlib.sha256((DIRECTORY/'source.glb').read_bytes()).hexdigest()!=manifest['sha256']:raise ValueError('Unverified source')
        subprocess.run(['/usr/bin/blender','--background','--threads','2','--python-exit-code','1','--python',str(Path(__file__).resolve()),'--','--worker'],check=True)
